export const BY_ID = Object.fromEntries(PRODUCTS.map((p) => [p.id, p])) as Record<string, Product>;

export const getProduct = (id?: string | null): Product | undefined => (id ? BY_ID[id] : undefined);

/** Resolve an article number or EAN typed or scanned by the user. */
export function lookupCode(raw: string): Product | undefined {
  const digits = raw.replace(/\D/g, '');
  if (!digits) return undefined;
  return PRODUCTS.find(
    (p) => p.article.replace(/\D/g, '') === digits || p.ean === digits || p.ean.endsWith(digits),
  );
}
